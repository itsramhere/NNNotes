package com.ramst.notein.editor

import android.content.Context
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.ramst.notein.storage.*
import kotlinx.coroutines.*
import org.junit.*
import org.junit.Assert.*
import org.junit.runner.RunWith
import java.util.UUID

@RunWith(AndroidJUnit4::class)
class Phase9StorageTest {
    private val context = ApplicationProvider.getApplicationContext<Context>()
    private val name = "phase9-${UUID.randomUUID()}.db"
    private lateinit var db: NoteinDatabase
    private lateinit var repo: EditorRepository
    private lateinit var notebooks: NotebookRepository
    private val template = PaperTemplate("dots", 792f, 612f, 3f, "fine", PaperColor.DARK_GRAY.argb)
    @Before fun setup() {
        db = Room.databaseBuilder(context, NoteinDatabase::class.java, name).build()
        repo = EditorRepository(db.editorDao()); notebooks = NotebookRepository(db.notebookDao(), db.folderDao())
    }
    @After fun cleanup() { db.close(); context.deleteDatabase(name) }
    private suspend fun notebook(type: NotebookType = NotebookType.STANDARD, automatic: Boolean = true) =
        notebooks.createNotebook("Phase9 fixture", null, type, template, automatic)
    private fun appearance(p: PageEntity) = PaperTemplate(p.paperBackground, p.pageWidth, p.pageHeight,
        p.paperSpacingMm, p.paperPatternWeight, p.paperBackgroundColor)

    @Test fun rapidCommitsAppendExactlyOnceKeepSelectionAndCopyOnlyTemplate() = runBlocking {
        val id = notebook(); val page = repo.firstPage(id)!!
        repo.selectPage(id, page.id)
        val ink = record(pageId = page.id).toEntity()
        coroutineScope { repeat(20) { launch(Dispatchers.IO) {
            repo.saveContentSnapshot(listOf(ink), page.copy(viewportX = -400f, viewportY = 70f, viewportScale = 2f))
        } } }
        val pages = repo.pages(id)
        assertEquals(2, pages.size); assertEquals(page.id, repo.notebook(id)!!.selectedPageId)
        assertEquals(template, appearance(pages.last())); assertTrue(pages.last().autoGenerated)
        assertEquals(0f, pages.last().viewportX, 0f); assertEquals(0f, pages.last().viewportY, 0f)
        assertEquals(1f, pages.last().viewportScale, 0f); assertTrue(repo.pageObjects(pages.last().id).isEmpty())
        repo.saveContentSnapshot(listOf(phase4Text(pages.last().id)), pages.last())
        assertEquals(3, repo.pages(id).size)
        repo.saveContentSnapshot(emptyList(), pages.last()) // Undo does not remove the successor.
        assertEquals(3, repo.pages(id).size)
    }

    @Test fun deletionNavigationAndErasingDoNotRegenerateUntilNewContentCommit() = runBlocking {
        val id = notebook(); val page = repo.firstPage(id)!!
        val first = record(pageId = page.id).toEntity(); val second = record(pageId = page.id, y = 180f).toEntity()
        repo.saveContentSnapshot(listOf(first, second), page)
        repo.deletePage(repo.pages(id).last().id, id)
        repo.saveContentSnapshot(listOf(first, second), page.copy(viewportScale = 2f))
        assertEquals("Viewport save must not allocate paper", 1, repo.pages(id).size)
        repo.saveContentSnapshot(listOf(first), page) // Erasing one of two strokes.
        assertEquals("Erasing must not allocate paper", 1, repo.pages(id).size)
        repo.saveContentSnapshot(listOf(first, second), page)
        assertEquals(2, repo.pages(id).size)
    }

    @Test fun emptyTextAndExcludedNotebookTypesNeverAppend() = runBlocking {
        val id = notebook(); val page = repo.firstPage(id)!!
        repo.saveContentSnapshot(listOf(phase4Text(page.id, text = "   \n")), page)
        assertEquals(1, repo.pages(id).size)
        repo.saveContentSnapshot(listOf(phase4Text(page.id, text = "Content")), page)
        assertEquals(2, repo.pages(id).size)
        val infinite = notebook(NotebookType.INFINITE); val canvas = repo.firstPage(infinite)!!
        repo.saveContentSnapshot(listOf(record(pageId = canvas.id).toEntity()), canvas)
        assertEquals(1, repo.pages(infinite).size)
        val pdfId = notebook()
        db.openHelper.writableDatabase.execSQL("UPDATE notebooks SET notebook_type='pdf' WHERE id=?", arrayOf(pdfId))
        val pdfPage = repo.firstPage(pdfId)!!
        repo.saveContentSnapshot(listOf(record(pageId = pdfPage.id).toEntity()), pdfPage)
        assertEquals(1, repo.pages(pdfId).size)
    }

    @Test fun allocationFailureAndInterruptedTransactionRetainSavedInkAndRetriesNeverMultiply() = runBlocking {
        val id = notebook(); val page = repo.firstPage(id)!!; val ink = record(pageId = page.id).toEntity()
        db.openHelper.writableDatabase.execSQL("CREATE TRIGGER phase9_full BEFORE INSERT ON pages BEGIN SELECT RAISE(ABORT,'injected full disk'); END")
        assertTrue(repo.saveContentSnapshot(listOf(ink), page).matchingPageAppendFailed)
        assertEquals(listOf(ink), repo.pageObjects(page.id)); assertEquals(1, repo.pages(id).size)
        repeat(3) { try { repo.retryMatchingPageAppend(page.id); fail("Expected allocation failure") } catch (_: Exception) {} }
        db.openHelper.writableDatabase.execSQL("DROP TRIGGER phase9_full")
        db.openHelper.writableDatabase.execSQL("CREATE TRIGGER phase9_interrupt BEFORE UPDATE ON notebooks BEGIN SELECT RAISE(ABORT,'interrupted allocation'); END")
        try { repo.retryMatchingPageAppend(page.id); fail("Expected rollback") } catch (_: Exception) {}
        assertEquals(1, repo.pages(id).size); assertEquals(listOf(ink), repo.pageObjects(page.id))
        db.openHelper.writableDatabase.execSQL("DROP TRIGGER phase9_interrupt")
        coroutineScope { repeat(12) { launch { repo.retryMatchingPageAppend(page.id) } } }
        assertEquals(2, repo.pages(id).size)
    }

    @Test fun templateLifecycleToggleAndDefaultExportRespectManualAndTouchedPages() = runBlocking {
        val id = notebook(automatic = false); val page = repo.firstPage(id)!!
        val ink = record(pageId = page.id).toEntity()
        repo.saveContentSnapshot(listOf(ink), page); assertEquals(1, repo.pages(id).size)
        val changed = PaperTemplate("grid", 420f, 595f, 10f, "bold", PaperColor.CREAM.argb)
        repo.updateNotebookTemplate(id, changed, true)
        repo.saveContentSnapshot(listOf(ink), page.copy(viewportX = -10f))
        assertEquals(1, repo.pages(id).size) // Toggle/reopen must wait for a new edit.
        repo.saveContentSnapshot(listOf(ink, phase4Image(page.id)), page)
        val automatic = repo.pages(id).last()
        assertEquals(template, appearance(automatic))
        assertEquals(listOf(page.id), repo.defaultExportSnapshot(id).map { it.first.id })
        assertEquals(automatic.id, repo.exportSnapshot(id, listOf(automatic.id)).single().first.id)
        val duplicate = repo.duplicatePage(automatic.id)
        assertFalse("Explicit duplicate is manual", db.editorDao().page(duplicate)!!.autoGenerated)
        assertEquals(3, repo.defaultExportSnapshot(id).size)
        val manual = repo.createPage(id, NotebookType.STANDARD)
        assertEquals(changed, appearance(db.editorDao().page(manual)!!))
        repo.updatePageTemplate(manual, template)
        assertEquals(changed, PaperTemplate(repo.notebook(id)!!.defaultPaperBackground, repo.notebook(id)!!.defaultPageWidth,
            repo.notebook(id)!!.defaultPageHeight, repo.notebook(id)!!.defaultSpacingMm, repo.notebook(id)!!.defaultPatternWeight,
            repo.notebook(id)!!.defaultBackgroundColor))
        repo.reorderPages(id, listOf(manual, duplicate, page.id, automatic.id))
        repo.deletePage(duplicate, id)
        assertEquals(template, appearance(db.editorDao().page(manual)!!))
        db.close(); db = Room.databaseBuilder(context, NoteinDatabase::class.java, name).build()
        repo = EditorRepository(db.editorDao())
        assertEquals("dots", repo.firstPage(id)!!.paperBackground)
        assertEquals(3, repo.pages(id).size)
    }
}
