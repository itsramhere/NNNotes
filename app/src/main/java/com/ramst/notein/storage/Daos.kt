@Dao
interface NotebookDao {
    @Query(
        """
        SELECT notebooks.id, notebooks.title, notebooks.folder_id AS folderId,
               folders.name AS folderName, notebooks.updated_at AS updatedAt,
               notebooks.trashed_at AS trashedAt, notebooks.notebook_type AS notebookType
        FROM notebooks
        LEFT JOIN folders ON notebooks.folder_id = folders.id
        WHERE notebooks.is_trashed = :trashed
          AND (:folderId IS NULL OR notebooks.folder_id = :folderId)
          AND LOWER(notebooks.title) LIKE '%' || LOWER(:query) || '%' ESCAPE '\'
        ORDER BY notebooks.updated_at DESC, notebooks.id ASC
        """,
    )
    fun observeNotebookList(
        trashed: Boolean,
        folderId: String?,
        query: String,
    ): Flow<List<NotebookListItem>>

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertNotebook(notebook: NotebookEntity)

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertPage(page: PageEntity)

    @Query("UPDATE notebooks SET title = :title, updated_at = :updatedAt WHERE id = :notebookId")
    suspend fun rename(notebookId: String, title: String, updatedAt: Long): Int

    @Query("UPDATE notebooks SET folder_id = :folderId, updated_at = :updatedAt WHERE id = :notebookId")
    suspend fun move(notebookId: String, folderId: String?, updatedAt: Long): Int

    @Query("UPDATE notebooks SET is_trashed = 1, trashed_at = :trashedAt, updated_at = :trashedAt WHERE id = :notebookId")
    suspend fun trash(notebookId: String, trashedAt: Long): Int

    @Query("UPDATE notebooks SET is_trashed = 0, trashed_at = NULL, updated_at = :updatedAt WHERE id = :notebookId")
    suspend fun restore(notebookId: String, updatedAt: Long): Int

    @Query("DELETE FROM notebooks WHERE id = :notebookId AND is_trashed = 1")
    suspend fun permanentlyDelete(notebookId: String): Int

    @Transaction
    suspend fun insertNotebookWithBlankPage(notebook: NotebookEntity, page: PageEntity) {
        insertNotebook(notebook)
        insertPage(page)
    }
}

@Dao
interface EditorDao {
    @Query("SELECT * FROM tool_preferences")
    suspend fun toolPreferences(): List<ToolPreferenceEntity>

    @Query("SELECT * FROM tool_preferences")
    fun observeToolPreferences(): Flow<List<ToolPreferenceEntity>>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun setToolPreference(value: ToolPreferenceEntity)

    @Query("UPDATE notebooks SET viewport_locked = :locked, locked_zoom_scale = :scale WHERE id = :notebookId")
    suspend fun setNotebookZoomLock(notebookId: String, locked: Boolean, scale: Float?): Int

    @Query("UPDATE pages SET viewport_scale = :scale WHERE notebook_id = :notebookId")
    suspend fun setNotebookPageScale(notebookId: String, scale: Float)

    @Transaction
    suspend fun setViewportLocked(notebookId: String, locked: Boolean, scale: Float?): Int {
        val changed = setNotebookZoomLock(notebookId, locked, scale)
        if (changed == 1 && locked && scale != null) setNotebookPageScale(notebookId, scale)
        return changed
    }

    @Query("UPDATE notebooks SET page_layout = :layout WHERE id = :notebookId")
    suspend fun setPageLayout(notebookId: String, layout: String): Int

    @Query("UPDATE pages SET viewport_width = :width, viewport_height = :height WHERE id = :pageId")
    suspend fun setViewportBounds(pageId: String, width: Float, height: Float)

    @Transaction
    suspend fun exportSnapshot(notebookId: String, pageIds: List<String>): List<Pair<PageEntity, List<EditableObjectEntity>>> {
        val available = pages(notebookId).associateBy { it.id }
        return pageIds.map { id ->
            val page = requireNotNull(available[id]) { "The selected page no longer exists." }
            page to pageObjects(id)
        }
    }

    /** Whole-notebook export omits only an untouched automatic trailing page. */
    @Transaction
    suspend fun defaultExportSnapshot(notebookId: String): List<Pair<PageEntity, List<EditableObjectEntity>>> {
        val orderedPages = pages(notebookId)
        val pagesToExport = if (orderedPages.size > 1 && orderedPages.lastOrNull()?.autoGenerated == true &&
            pageObjects(orderedPages.last().id).isEmpty()) orderedPages.dropLast(1) else orderedPages
        return pagesToExport.map { page -> page to pageObjects(page.id) }
    }

    @Query("SELECT editable_objects.* FROM editable_objects INNER JOIN pages ON pages.id = editable_objects.page_id WHERE pages.notebook_id = :notebookId ORDER BY editable_objects.created_at, editable_objects.id")
    fun observeNotebookObjects(notebookId: String): Flow<List<EditableObjectEntity>>

    @Query("UPDATE notebooks SET selected_page_id = :pageId WHERE id = :notebookId AND EXISTS (SELECT 1 FROM pages WHERE id = :pageId AND notebook_id = :notebookId)")
    suspend fun selectPage(notebookId: String, pageId: String): Int

    @Query("SELECT * FROM notebooks WHERE id = :notebookId AND is_trashed = 0 LIMIT 1")
    suspend fun notebook(notebookId: String): NotebookEntity?

    @Query("SELECT * FROM pages WHERE notebook_id = :notebookId ORDER BY sort_index ASC")
    fun observePages(notebookId: String): Flow<List<PageEntity>>

    @Query("SELECT * FROM pages WHERE notebook_id = :notebookId ORDER BY sort_index ASC")
    suspend fun pages(notebookId: String): List<PageEntity>

    @Query("SELECT * FROM pages WHERE id = :pageId LIMIT 1")
    suspend fun page(pageId: String): PageEntity?

    @Query("SELECT COUNT(*) FROM pages WHERE notebook_id = :notebookId")
    suspend fun pageCount(notebookId: String): Int

    @Query("SELECT COALESCE(MAX(sort_index), -1) + 1 FROM pages WHERE notebook_id = :notebookId")
    suspend fun nextPageSortIndex(notebookId: String): Int

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertPage(page: PageEntity)

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertObjects(objects: List<EditableObjectEntity>)

    @Query("DELETE FROM pages WHERE id = :pageId AND notebook_id = :notebookId")
    suspend fun deletePage(pageId: String, notebookId: String): Int

    @Query("UPDATE pages SET sort_index = :sortIndex, updated_at = :updatedAt WHERE id = :pageId AND notebook_id = :notebookId")
    suspend fun updatePageSortIndex(pageId: String, notebookId: String, sortIndex: Int, updatedAt: Long): Int

    @Query("UPDATE pages SET sort_index = -sort_index - 1 WHERE notebook_id = :notebookId")
    suspend fun movePageSortIndicesOutOfTheWay(notebookId: String): Int

    @Query("UPDATE pages SET paper_background = :background, updated_at = :updatedAt WHERE id = :pageId")
    suspend fun updatePageBackground(pageId: String, background: String, updatedAt: Long): Int

    @Query("UPDATE pages SET paper_background = :background, page_width = :width, page_height = :height, paper_spacing_mm = :spacingMm, paper_pattern_weight = :weight, paper_background_color = :color, updated_at = :updatedAt WHERE id = :pageId")
    suspend fun updatePageTemplate(pageId: String, background: String, width: Float, height: Float, spacingMm: Float, weight: String, color: Int, updatedAt: Long): Int

    @Query("UPDATE notebooks SET default_paper_background = :background, default_page_width = :width, default_page_height = :height, default_spacing_mm = :spacingMm, default_pattern_weight = :weight, default_background_color = :color, auto_matching_pages = :autoMatchingPages, updated_at = :updatedAt WHERE id = :notebookId")
    suspend fun updateNotebookTemplate(notebookId: String, background: String, width: Float, height: Float, spacingMm: Float, weight: String, color: Int, autoMatchingPages: Boolean, updatedAt: Long): Int

    @Query("UPDATE pages SET auto_generated = 0 WHERE id = :pageId")
    suspend fun markPageTouched(pageId: String): Int

    @Query("SELECT * FROM editable_objects WHERE page_id = :pageId")
    suspend fun pageObjects(pageId: String): List<EditableObjectEntity>

    @Query("SELECT * FROM editable_objects WHERE id = :objectId")
    suspend fun objectById(objectId: String): EditableObjectEntity?

    @Upsert
    suspend fun upsertObjects(objects: List<EditableObjectEntity>)

    /** Reconcile ink only, preserving unknown/future editable object types. */
    @Transaction
    suspend fun saveInkSnapshot(objects: List<EditableObjectEntity>, state: PageEntity, updatedAt: Long) {
        require(objects.all { it.pageId == state.id && it.type == "ink_stroke_v1" })
        require(objects.map { it.id }.distinct().size == objects.size)
        val existing = pageObjects(state.id).associateBy { it.id }
        val desired = objects.associateBy { it.id }
        check(objects.all { existing[it.id]?.type?.let { type -> type == "ink_stroke_v1" } != false }) {
            "Ink cannot replace another object type."
        }
        objects.filter { it.id !in existing }.forEach {
            check(objectById(it.id) == null) { "This object belongs to a different page." }
        }
        existing.values.filter { it.type == "ink_stroke_v1" && it.id !in desired }.forEach {
            check(deleteObject(it.id, state.id) == 1) { "The stroke no longer exists." }
        }
        upsertObjects(objects.filter { existing[it.id] != it })
        updateEditorStateAndTouchNotebook(state, updatedAt)
    }

    /** Reconcile the editor's complete supported content; retain unknown future types. */
    @Transaction
    suspend fun saveContentSnapshot(objects: List<EditableObjectEntity>, state: PageEntity, updatedAt: Long): Boolean {
        val supportedTypes = com.ramst.notein.editor.EDITABLE_CONTENT_TYPES
        require(objects.all { it.pageId == state.id && it.type in supportedTypes })
        require(objects.map { it.id }.distinct().size == objects.size)
        check(page(state.id)?.notebookId == state.notebookId) { "The page no longer exists." }
        val existing = pageObjects(state.id).associateBy { it.id }
        val desiredIds = objects.map { it.id }.toSet()
        objects.forEach { objectEntity ->
            val old = existing[objectEntity.id] ?: objectById(objectEntity.id)
            check(old == null || (old.pageId == state.id && old.type == objectEntity.type)) {
                "Content cannot overwrite another page or object type."
            }
        }
        existing.values.filter { it.type in supportedTypes && it.id !in desiredIds }.forEach {
            check(deleteObject(it.id, state.id) == 1) { "The object no longer exists." }
        }
        val changed = objects.filter { existing[it.id]?.payload != it.payload || existing[it.id]?.type != it.type }
        val qualifies = changed.any { it.isNonemptyPageContent() }
        upsertObjects(objects.filter { existing[it.id] != it })
        if (qualifies) markPageTouched(state.id)
        updateEditorStateAndTouchNotebook(state, updatedAt)
        setViewportBounds(state.id, state.viewportWidth, state.viewportHeight)
        return qualifies
    }
    @Query("SELECT * FROM pages WHERE notebook_id = :notebookId ORDER BY sort_index ASC LIMIT 1")
    suspend fun firstPage(notebookId: String): PageEntity?

    @Query("SELECT * FROM editable_objects WHERE page_id = :pageId ORDER BY created_at ASC, id ASC")
    fun observePageObjects(pageId: String): Flow<List<EditableObjectEntity>>

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertObject(editableObject: EditableObjectEntity)

    @Query("DELETE FROM editable_objects WHERE id = :objectId AND page_id = :pageId")
    suspend fun deleteObject(objectId: String, pageId: String): Int

    @Query(
        """
        UPDATE pages
        SET viewport_x = :viewportX,
            viewport_y = :viewportY,
            viewport_scale = COALESCE((SELECT locked_zoom_scale FROM notebooks WHERE notebooks.id = pages.notebook_id AND viewport_locked = 1), :viewportScale),
            active_tool = :activeTool,
            brush_color = :brushColor,
            brush_size = :brushSize,
            finger_writing = :fingerWriting,
            updated_at = :updatedAt
        WHERE id = :pageId
        """,
    )
    suspend fun updatePageEditorState(
        pageId: String,
        viewportX: Float,
        viewportY: Float,
        viewportScale: Float,
        activeTool: String,
        brushColor: Int,
        brushSize: Float,
        fingerWriting: Boolean,
        updatedAt: Long,
    ): Int

    @Query(
        """
        UPDATE notebooks
        SET updated_at = :updatedAt
        WHERE id = (SELECT notebook_id FROM pages WHERE id = :pageId)
        """,
    )
    suspend fun touchNotebookForPage(pageId: String, updatedAt: Long): Int

    @Query("UPDATE notebooks SET updated_at = :updatedAt WHERE id = :notebookId")
    suspend fun touchNotebook(notebookId: String, updatedAt: Long): Int

    @Transaction
    suspend fun saveStrokeAndEditorState(
        editableObject: EditableObjectEntity,
        state: PageEntity,
        updatedAt: Long,
    ) {
        require(editableObject.pageId == state.id) { "Stroke and state must belong to the same page." }
        insertObject(editableObject)
        check(
            updatePageEditorState(
                pageId = state.id,
                viewportX = state.viewportX,
                viewportY = state.viewportY,
                viewportScale = state.viewportScale,
                activeTool = state.activeTool,
                brushColor = state.brushColor,
                brushSize = state.brushSize,
                fingerWriting = state.fingerWriting,
                updatedAt = updatedAt,
            ) == 1,
        ) { "The page no longer exists." }
        check(touchNotebookForPage(state.id, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun deleteStrokeAndTouchNotebook(pageId: String, objectId: String, updatedAt: Long) {
        check(deleteObject(objectId, pageId) == 1) { "The stroke no longer exists." }
        check(touchNotebookForPage(pageId, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun updateEditorStateAndTouchNotebook(state: PageEntity, updatedAt: Long) {
        setViewportBounds(state.id, state.viewportWidth, state.viewportHeight)
        check(
            updatePageEditorState(
                pageId = state.id,
                viewportX = state.viewportX,
                viewportY = state.viewportY,
                viewportScale = state.viewportScale,
                activeTool = state.activeTool,
                brushColor = state.brushColor,
                brushSize = state.brushSize,
                fingerWriting = state.fingerWriting,
                updatedAt = updatedAt,
            ) == 1,
        ) { "The page no longer exists." }
        check(touchNotebookForPage(state.id, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun createPageAndTouchNotebook(page: PageEntity, updatedAt: Long) {
        check(notebook(page.notebookId)?.notebookType in setOf(NotebookType.STANDARD.storageValue, NotebookType.PDF.storageValue)) { "This notebook cannot add pages." }
        insertPage(page.copy(sortIndex = nextPageSortIndex(page.notebookId)))
        check(touchNotebookForPage(page.id, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun duplicatePageAndTouchNotebook(
        sourcePageId: String,
        duplicateId: String,
        updatedAt: Long,
    ) {
        val source = requireNotNull(page(sourcePageId)) { "The source page no longer exists." }
        check(notebook(source.notebookId)?.notebookType in setOf(NotebookType.STANDARD.storageValue, NotebookType.PDF.storageValue)) { "This notebook cannot duplicate pages." }
        val duplicate = source.copy(id = duplicateId, sortIndex = nextPageSortIndex(source.notebookId), createdAt = updatedAt, updatedAt = updatedAt, autoGenerated = false)
        val copiedObjects = pageObjects(sourcePageId)
            .sortedWith(compareBy<EditableObjectEntity> { it.createdAt }.thenBy { it.id })
            .mapIndexed { index, objectEntity -> objectEntity.copy(
                id = java.util.UUID.randomUUID().toString(), pageId = duplicateId,
                createdAt = updatedAt + index, updatedAt = updatedAt) }
        insertPage(duplicate)
        insertObjects(copiedObjects)
        check(touchNotebookForPage(duplicate.id, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun deletePageAndTouchNotebook(pageId: String, notebookId: String, updatedAt: Long) {
        check(pageCount(notebookId) > 1) { "A notebook must keep at least one page." }
        check(deletePage(pageId, notebookId) == 1) { "The page no longer exists." }
        val remaining = pages(notebookId)
        reorderPagesAndTouchNotebook(notebookId, remaining.map { it.id }, updatedAt)
        val notebook = notebook(notebookId)
        if (notebook?.selectedPageId == pageId) selectPage(notebookId, remaining.first().id)
        check(touchNotebook(notebookId, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun reorderPagesAndTouchNotebook(notebookId: String, orderedPageIds: List<String>, updatedAt: Long) {
        val existing = pages(notebookId)
        require(existing.map { it.id }.toSet() == orderedPageIds.toSet() && existing.size == orderedPageIds.size) {
            "The page order does not match this notebook."
        }
        movePageSortIndicesOutOfTheWay(notebookId)
        orderedPageIds.forEachIndexed { index, pageId ->
            check(updatePageSortIndex(pageId, notebookId, index, updatedAt) == 1) { "The page no longer exists." }
        }
        if (existing.isNotEmpty()) check(touchNotebook(notebookId, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun updatePageBackgroundAndTouchNotebook(pageId: String, background: String, updatedAt: Long) {
        val source = requireNotNull(page(pageId)) { "The page no longer exists." }
        check(source.pdfPageIndex == null) { "Imported PDF paper cannot be changed." }
        check(updatePageBackground(pageId, background, updatedAt) == 1) { "The page no longer exists." }
        markPageTouched(pageId)
        check(touchNotebookForPage(pageId, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun updatePageTemplateAndTouchNotebook(pageId: String, template: PaperTemplate, updatedAt: Long) {
        val source = requireNotNull(page(pageId)) { "The page no longer exists." }
        check(source.pdfPageIndex == null) { "Imported PDF paper cannot be changed." }
        check(updatePageTemplate(pageId, template.background, template.width, template.height, template.spacingMm,
            template.patternWeight, template.backgroundColor, updatedAt) == 1) { "The page no longer exists." }
        markPageTouched(pageId)
        check(touchNotebookForPage(pageId, updatedAt) == 1) { "The notebook no longer exists." }
    }

    @Transaction
    suspend fun appendMatchingPageIfNeeded(pageId: String, now: Long): String? {
        val source = requireNotNull(page(pageId)) { "The page no longer exists." }
        val notebook = requireNotNull(notebook(source.notebookId)) { "The notebook no longer exists." }
        if (source.pdfPageIndex != null || notebook.notebookType != NotebookType.STANDARD.storageValue || !notebook.autoMatchingPages) return null
        val pages = pages(source.notebookId)
        if (pages.lastOrNull()?.id != pageId || pageObjects(pageId).none { it.isNonemptyPageContent() }) return null
        val next = source.copy(
            id = java.util.UUID.randomUUID().toString(),
            sortIndex = nextPageSortIndex(source.notebookId),
            createdAt = now,
            updatedAt = now,
            viewportX = 0f,
            viewportY = 0f,
            viewportScale = notebook.lockedZoomScale.takeIf { notebook.viewportLocked } ?: 1f,
            viewportWidth = 0f,
            viewportHeight = 0f,
            activeTool = source.activeTool,
            autoGenerated = true,
        )
        insertPage(next)
        check(touchNotebook(source.notebookId, now) == 1) { "The notebook no longer exists." }
        return next.id
    }
}

@Dao
interface PdfDao {
    @Query("SELECT local_path FROM pdf_documents")
    suspend fun allSourcePaths(): List<String>
    @Query("SELECT COUNT(*) FROM pages WHERE pdf_source_id = :sourceId")
    suspend fun sourcePageReferences(sourceId: String): Int

    @Query("SELECT * FROM editable_objects WHERE type = 'pdf_page_v1'")
    suspend fun pdfObjects(): List<EditableObjectEntity>

    @Query("DELETE FROM pdf_documents WHERE source_id = :sourceId")
    suspend fun deleteSource(sourceId: String)

    @Query("SELECT COUNT(*) FROM pdf_documents WHERE local_path = :path")
    suspend fun pathReferences(path: String): Int

    @Transaction
    suspend fun releaseUnusedSources(notebookId: String): List<PdfDocumentEntity> {
        val objectSources = pdfObjects().mapNotNull {
            runCatching { org.json.JSONObject(it.payload).getString("pdfSourceId") }.getOrNull()
        }.toSet()
        val unused = documents(notebookId).filter { it.sourceId !in objectSources && sourcePageReferences(it.sourceId) == 0 }
        unused.forEach { deleteSource(it.sourceId) }
        return unused
    }
    @Query("SELECT * FROM pdf_documents WHERE notebook_id = :notebookId ORDER BY created_at, source_id")
    suspend fun documents(notebookId: String): List<PdfDocumentEntity>

    @Query("SELECT * FROM pdf_documents WHERE source_id = :sourceId")
    suspend fun source(sourceId: String): PdfDocumentEntity?

    @Query("SELECT * FROM pages WHERE notebook_id = :notebookId ORDER BY sort_index")
    suspend fun pages(notebookId: String): List<PageEntity>

    @Query("SELECT * FROM notebooks WHERE id = :notebookId")
    suspend fun importNotebook(notebookId: String): NotebookEntity?

    @Query("UPDATE pages SET sort_index = :index WHERE id = :pageId")
    suspend fun movePage(pageId: String, index: Int)

    @Query("UPDATE notebooks SET updated_at = :now WHERE id = :notebookId AND is_trashed = 0")
    suspend fun touch(notebookId: String, now: Long): Int

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertObjects(objects: List<EditableObjectEntity>)

    @Transaction
    suspend fun insertIntoNotebook(document: PdfDocumentEntity, afterPageId: String, importedPages: List<PageEntity>, objects: List<EditableObjectEntity>) {
        val existing = pages(document.notebookId)
        val position = existing.indexOfFirst { it.id == afterPageId }
        check(position >= 0 && touch(document.notebookId, document.createdAt) == 1) { "The target notebook changed." }
        check(source(document.sourceId) == null) { "This PDF has already been inserted." }
        insertDocument(document)
        if (importedPages.isNotEmpty()) {
            existing.forEachIndexed { index, page -> movePage(page.id, -index - 1) }
            val notebook = requireNotNull(importNotebook(document.notebookId))
            insertPages(importedPages.mapIndexed { index, page -> page.copy(sortIndex = existing.size + index,
                viewportScale = notebook.lockedZoomScale.takeIf { notebook.viewportLocked } ?: page.viewportScale) })
            val ordered = existing.take(position + 1) + importedPages + existing.drop(position + 1)
            ordered.forEachIndexed { index, page -> movePage(page.id, index) }
        }
        if (objects.isNotEmpty()) insertObjects(objects)
    }
    @Query("SELECT * FROM pdf_documents WHERE notebook_id = :notebookId LIMIT 1")
    suspend fun document(notebookId: String): PdfDocumentEntity?

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertDocument(document: PdfDocumentEntity)

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertNotebook(notebook: NotebookEntity)

    @Insert(onConflict = OnConflictStrategy.ABORT)
    suspend fun insertPages(pages: List<PageEntity>)

    @Transaction
    suspend fun insertPdfNotebook(notebook: NotebookEntity, document: PdfDocumentEntity, pages: List<PageEntity>) {
        require(notebook.notebookType == NotebookType.PDF.storageValue)
        require(document.notebookId == notebook.id)
        require(pages.isNotEmpty() && pages.all { it.notebookId == notebook.id && it.pdfPageIndex != null })
        insertNotebook(notebook)
        insertDocument(document)
        insertPages(pages)
    }
}
